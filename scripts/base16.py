"""Vendor a pinned Base16 registry, or regenerate its C table from vendored JSON.

Refresh: uv run python scripts/base16.py --upstream build/base16-upstream
The upstream checkout is https://github.com/tinted-theming/schemes (MIT).
No network access or YAML dependency is required to regenerate the table.
"""

import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--upstream", type=Path)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
registry = ROOT / "third_party/base16.json"
if args.upstream:
    schemes = []
    for path in sorted((args.upstream / "base16").glob("*.yaml"), key=lambda path: path.stem):
        source = path.read_text(encoding="utf-8")
        palette = dict(re.findall(r"base([0-9A-Fa-f]{2}):\s*[\"\']?#?([0-9A-Fa-f]{6})", source))
        colors = {key.upper(): value.lower() for key, value in palette.items()}
        assert set(colors) == {f"{i:02X}" for i in range(16)}, path
        schemes.append({"name": path.stem, "yaml": source, "colors": [colors[f"{i:02X}"] for i in range(16)]})
    commit = subprocess.check_output(["git", "-C", str(args.upstream), "rev-parse", "HEAD"], text=True).strip()
    data = {"source": "https://github.com/tinted-theming/schemes", "commit": commit, "schemes": schemes}
    registry.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    (ROOT / "third_party/BASE16_LICENSE.md").write_text(
        (args.upstream / "LICENSE").read_text(encoding="utf-8"), encoding="utf-8", newline="\n"
    )
else:
    data = json.loads(registry.read_text(encoding="utf-8"))

# Prefer exact dark/light counterparts. These families use published variant
# names that cannot be derived by replacing a "dark" or "light" component.
# The first two entries are the canonical dark and light selections.
families = [
    ("ayu-dark", "ayu-light", "ayu-mirage"),
    ("catppuccin-mocha", "catppuccin-latte", "catppuccin-frappe", "catppuccin-macchiato"),
    ("chicago-night", "chicago-day"),
    ("chinoiserie-night", "chinoiserie", "chinoiserie-midnight", "chinoiserie-morandi"),
    ("da-one-black", "da-one-paper", "da-one-gray", "da-one-ocean", "da-one-sea", "da-one-white"),
    ("everforest-dark-medium", "everforest-light-medium", "everforest"),
    ("github-dark", "github", "github-dark-dimmed"),
    ("gruvbox-dark-medium", "gruvbox-light-medium", "gruvbox-dark-medium-forest", "gruvbox-dark-pale"),
    ("kissa-macchiato", "kissa-latte"),
    ("material", "material-lighter", "material-darker", "material-palenight", "material-vivid"),
    ("onedark", "one-light", "onedark-dark"),
    ("precious-dark-eleven", "precious-light-warm", "precious-dark-fifteen", "precious-light-white"),
    ("primer-dark", "primer-light", "primer-dark-dimmed"),
    ("rose-pine", "rose-pine-dawn", "rose-pine-moon"),
    ("selenized-dark", "selenized-light", "selenized-black", "selenized-white"),
    ("serendipity-midnight", "serendipity-morning", "serendipity-sunset"),
    ("tokyo-night-dark", "tokyo-night-light", "tokyo-night-moon", "tokyo-night-storm"),
    ("tokyo-night-terminal-dark", "tokyo-night-terminal-light", "tokyo-night-terminal-storm"),
    ("tomorrow-night", "tomorrow", "tomorrow-night-eighties"),
]
schemes_by_name = {s["name"]: s for s in data["schemes"]}
for scheme in data["schemes"]:
    match = re.search(r'^variant:\s*"?(dark|light)', scheme["yaml"], re.MULTILINE)
    assert match, scheme["name"]
    scheme["variant"] = match[1]
for scheme in data["schemes"]:
    name, natural = scheme["name"], scheme["variant"]
    for variant in ("dark", "light"):
        candidates = [name] if natural == variant else []
        candidates += ["-".join(variant if part == natural else part for part in name.split("-"))]
        candidates += [name + "-" + variant]
        if name.endswith("-" + natural):
            candidates += [name.removesuffix("-" + natural)]
        for dark, light, *others in families:
            if name in (dark, light, *others):
                candidates += [dark if variant == "dark" else light]
        scheme[variant] = next(
            (
                candidate
                for candidate in candidates
                if candidate in schemes_by_name and schemes_by_name[candidate]["variant"] == variant
            ),
            None,
        )
if args.upstream:
    registry.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")

lines = [
    "/* Generated by scripts/base16.py; source and per-scheme attribution: third_party/base16.json. */",
    "// clang-format off",
    "static const struct { const char *name; sequel_colorscheme_t palette; sequel_appearance_t appearance; "
    "const char *dark, *light; } highlight_schemes[] = {",
]
for scheme in data["schemes"]:
    assert re.fullmatch(r"[a-z0-9-]+", scheme["name"]), scheme["name"]
    colors = ", ".join("0x" + value for value in scheme["colors"])
    dark = json.dumps(scheme["dark"]) if scheme["dark"] else "NULL"
    light = json.dumps(scheme["light"]) if scheme["light"] else "NULL"
    lines.append(
        '  {"'
        + scheme["name"]
        + '", {{'
        + colors
        + "}}, SEQUEL_APPEARANCE_"
        + scheme["variant"].upper()
        + ", "
        + dark
        + ", "
        + light
        + "},"
    )
lines.extend(["};", "// clang-format on", ""])
generated = "\n".join(lines)
target = ROOT / "src/sql/base16.h"
if args.check:
    if target.read_text(encoding="utf-8") != generated:
        raise SystemExit("Run uv run python scripts/base16.py to regenerate the palette table")
else:
    target.write_text(generated, encoding="utf-8", newline="\n")
